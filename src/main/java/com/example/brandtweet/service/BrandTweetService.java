
package com.example.brandtweet.service;

import com.example.brandtweet.model.GenerateRequest;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;
import org.springframework.http.HttpStatus;

@Service
public class BrandTweetService {

    public String generate(GenerateRequest request) {

        String brand = safe(request.getBrandName());
        String industry = safe(request.getIndustry());
        String objective = safe(request.getObjective());
        String products = safe(request.getProductDetails());
        String tone = safe(request.getTone());
        String audience = safe(request.getTargetAudience());

        if (brand.isBlank() && industry.isBlank() && products.isBlank()) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST,
                    "Please enter a brand name, industry, or product details."
            );
        }

        if (brand.isBlank()) {
            brand = "Our Brand";
        }

        if (industry.isBlank()) {
            industry = "our industry";
        }

        if (products.isBlank()) {
            products = "our products and services";
        }

        if (objective.isBlank()) {
            objective = "increase engagement";
        }

        if (tone.isBlank()) {
            tone = "friendly";
        }

        if (audience.isBlank()) {
            audience = "our audience";
        }

        StringBuilder result = new StringBuilder();

        result.append("# Brand Voice Summary\n\n");
        result.append("- **Brand:** ").append(brand).append("\n");
        result.append("- **Industry:** ").append(industry).append("\n");
        result.append("- **Tone:** ").append(tone).append("\n");
        result.append("- **Target Audience:** ").append(audience).append("\n");
        result.append("- **Campaign Objective:** ").append(objective).append("\n");
        result.append("- **Content Theme:** Introduce the brand, highlight products, ")
              .append("share useful information, and encourage engagement.\n\n");

        result.append("# 10 Generated Tweets\n\n");

        String[] tweets = {
            "Meet " + brand + "! Discover more about what we do in " + industry + ".",
            "Looking for " + products + "? Explore what " + brand + " has to offer.",
            "Our goal is simple: " + objective + ". Thanks for being part of our journey!",
            "Every great journey starts with one step. Let's take the next step together! #"
                    + cleanHashtag(brand),
            "What matters most to you when choosing " + products + "? Tell us below!",
            "At " + brand + ", we believe in keeping things " + tone + ". Stay connected with us!",
            "Here's your reminder to explore new possibilities in " + industry + ".",
            "Your opinion matters! What would you like to see next from " + brand + "?",
            "Discover, learn, and grow with " + brand + ". Follow us for more updates!",
            "Hey " + audience + ", let's start a conversation! What topics related to "
                    + industry + " interest you most?"
        };

        String[] styles = {
            "Brand Introduction",
            "Promotional",
            "Engagement",
            "Motivational",
            "Question",
            "Brand Personality",
            "Informative",
            "Community Engagement",
            "Brand Awareness",
            "Conversational"
        };

        for (int i = 0; i < tweets.length; i++) {
            result.append("### ").append(i + 1).append(". ")
                  .append(styles[i]).append("\n");
            result.append(tweets[i]).append("\n\n");
        }

        result.append("---\n");
        result.append("*Note: These tweets are generated from local templates. ")
              .append("They are not generated by an AI model.*");

        return result.toString();
    }

    private String safe(String value) {
        return value == null ? "" : value.trim();
    }

    private String cleanHashtag(String value) {
        String hashtag = value.replaceAll("[^a-zA-Z0-9]", "");
        return hashtag.isBlank() ? "OurBrand" : hashtag;
    }
}
